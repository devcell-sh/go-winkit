package imageformat

import (
	"fmt"
	"os"
	"strings"
	"text/template"
)

// VagrantOpts parameterizes the generated Vagrantfile. The zero value is
// filled with the same defaults the build VM uses.
type VagrantOpts struct {
	// ImageName is the qcow2 filename relative to the Vagrantfile.
	// Required for the box-less Vagrantfile; ignored for Box packaging
	// (the box supplies the disk itself).
	ImageName string
	// Box selects the variant embedded in a .box package: no image_path
	// (vagrant copies the box's disk per machine).
	Box bool
	// Username and Password are the Windows account provisioned by the build.
	Username string
	Password string
	// Hostname is passed as the SMBIOS serial; the image's boot task
	// renames the guest to it (effective from the second boot).
	Hostname string
	// SSHPort is the host port vagrant-qemu forwards to the guest's OpenSSH.
	SSHPort int
	// RDPPort is the host port forwarded to the guest's RDP (:3389).
	RDPPort  int
	MemoryGB int
	CPUs     int
}

func (o VagrantOpts) withDefaults() VagrantOpts {
	if o.SSHPort == 0 {
		o.SSHPort = 50022
	}
	if o.RDPPort == 0 {
		o.RDPPort = 23389
	}
	if o.MemoryGB == 0 {
		o.MemoryGB = 6
	}
	if o.CPUs == 0 {
		o.CPUs = 4
	}
	if o.Hostname == "" {
		o.Hostname = "winkit"
	}
	return o
}

// RenderVagrantfile renders the vagrant-qemu Vagrantfile for opts.
func RenderVagrantfile(opts VagrantOpts) (string, error) {
	if !opts.Box && opts.ImageName == "" {
		return "", fmt.Errorf("vagrantfile: ImageName is required")
	}
	var buf strings.Builder
	if err := vagrantTmpl.Execute(&buf, opts.withDefaults()); err != nil {
		return "", fmt.Errorf("rendering Vagrantfile: %w", err)
	}
	return buf.String(), nil
}

// WriteVagrantfile renders a vagrant-qemu Vagrantfile at dest that boots the
// built qcow2 box-less (no vagrant box needed): the user just runs
// "vagrant up" (the plugin auto-installs on first run).
func WriteVagrantfile(dest string, opts VagrantOpts) error {
	content, err := RenderVagrantfile(opts)
	if err != nil {
		return err
	}
	if err := os.WriteFile(dest, []byte(content), 0o644); err != nil {
		return fmt.Errorf("writing Vagrantfile: %w", err)
	}
	return nil
}

// WriteBoxVagrantfile writes a minimal consumer Vagrantfile next to a
// .box package: "vagrant up" auto-adds the box from the local file and
// installs the provider plugin on first run. Credentials, ports, and
// provider config come from the Vagrantfile embedded in the box itself.
func WriteBoxVagrantfile(dest, boxFile, boxName string) error {
	var buf strings.Builder
	err := vagrantBoxConsumerTmpl.Execute(&buf, struct{ BoxFile, BoxName string }{boxFile, boxName})
	if err != nil {
		return fmt.Errorf("rendering box Vagrantfile: %w", err)
	}
	if err := os.WriteFile(dest, []byte(buf.String()), 0o644); err != nil {
		return fmt.Errorf("writing Vagrantfile: %w", err)
	}
	return nil
}

var vagrantBoxConsumerTmpl = template.Must(template.New("vagrantfile-box").Parse(`# Vagrantfile generated by winkit
#
# Boots {{.BoxFile}}. Requires vagrant and QEMU on PATH. Just run:
#   vagrant up
# It adds the box from the local file and installs the vagrant-qemu
# plugin on first run. Credentials and ports are embedded in the box.
Vagrant.configure("2") do |config|
  config.vagrant.plugins = ["vagrant-qemu"]
  config.vm.box = "{{.BoxName}}"
  config.vm.box_url = "file://" + File.expand_path("{{.BoxFile}}", __dir__)
end
`))

var vagrantTmpl = template.Must(template.New("vagrantfile").Parse(`# Vagrantfile generated by winkit
#
# Requires vagrant and QEMU on PATH (any install source: brew, nix,
# MacPorts). Then:
#   vagrant up        # boots the Windows VM headless (offers to
#                     # install the vagrant-qemu plugin on first run)
#   vagrant ssh       # SSH into it (user: {{.Username}})
#   vagrant halt      # shut down
#
# RDP (GUI): 127.0.0.1:{{.RDPPort}} with the same credentials (may be
# auto-corrected on collision — check with: vagrant port).
{{- if not .Box}}
#
# The VM boots {{.ImageName}} in place — copy the qcow2 first if you
# want to keep the base image pristine.
{{- end}}

# vagrant-qemu runs the qemu-system-aarch64 from PATH, but also needs
# QEMU's data dir (edk2 firmware) as a path, and its default only covers
# Homebrew on Apple Silicon (/opt/homebrew/share/qemu). Ask QEMU itself:
# "-L help" lists its data dirs; take the first that exists.
qemu_bin = ` + "`which qemu-system-aarch64 2>/dev/null`" + `.strip
abort "qemu-system-aarch64 not found on PATH — install QEMU first" if qemu_bin.empty?
qemu_dir = ` + "`#{qemu_bin} -L help 2>/dev/null`" + `.lines.map(&:strip).find { |d| File.directory?(d) }

Vagrant.configure("2") do |config|
  # Auto-install the provider plugin on first "vagrant up".
  config.vagrant.plugins = ["vagrant-qemu"]

  config.vm.guest = :windows
  config.vm.communicator = "winssh"
  # Defaults are the account baked into the image at build time; override
  # per caller via env when the image was built with different creds:
  #   WINKIT_USERNAME=alice WINKIT_PASSWORD=secret vagrant up
  config.winssh.username = ENV.fetch("WINKIT_USERNAME", "{{.Username}}")
  config.winssh.password = ENV.fetch("WINKIT_PASSWORD", "{{.Password}}")
  # Mirrored into config.ssh: parts of vagrant (the boot banner, some
  # communicator paths) read ssh rather than winssh, and without a
  # password there it falls back to user "vagrant" + insecure key auth.
  config.ssh.username = ENV.fetch("WINKIT_USERNAME", "{{.Username}}")
  config.ssh.password = ENV.fetch("WINKIT_PASSWORD", "{{.Password}}")
  # Password auth is the image's contract — skip vagrant's generated-key
  # insertion (an SFTP upload the guest's sshd may not serve).
  config.ssh.insert_key = false
  config.winssh.insert_key = false
  config.vm.boot_timeout = 600
  config.vm.synced_folder ".", "/vagrant", disabled: true

  # RDP (GUI). auto_correct lets Vagrant pick a free host port on
  # collision (vagrant port shows the actual mapping).
  config.vm.network "forwarded_port", guest: 3389, host: {{.RDPPort}}, id: "rdp", auto_correct: true

  config.vm.provider "qemu" do |qe|
{{- if not .Box}}
    qe.image_path = File.expand_path("{{.ImageName}}", __dir__)
{{- end}}
    qe.arch = "aarch64"
    qe.machine = "virt,accel=hvf"
    qe.cpu = "host"
    qe.smp = {{.CPUs}}
    qe.memory = "{{.MemoryGB}}G"
    # Device model must match the drivers in the image: the disk goes on
    # NVMe (Windows' inbox driver — winkit builds and boots the image
    # that way; there is no virtio-blk driver installed, so the plugin's
    # default MMIO disk is invisible to Windows) and the NIC must be the
    # PCI virtio variant (NetKVM is a PCI driver).
    qe.drive_interface = "none"
    qe.net_device = "virtio-net-pci"
    # vagrant-qemu manages the SSH forward itself; ssh_auto_correct lets
    # it pick a free host port on collision (vagrant port shows the
    # actual mapping). Pin one per VM: WINKIT_SSH_PORT=… vagrant up
    qe.ssh_port = Integer(ENV.fetch("WINKIT_SSH_PORT", {{.SSHPort}}))
    qe.ssh_auto_correct = true
    # Mirrors the argv "winkit start" builds (vm/qemu): nvme drives the
    # disk0 declared by drive_interface = "none" above, ramfb is the
    # display device. The SMBIOS serial is read by the image's boot
    # task, which renames the guest to it (hostname + NetBIOS name,
    # effective from the second boot).
    qe.extra_qemu_args = [
      "-device", "nvme,drive=disk0,serial=winkit0,bootindex=0",
      "-device", "ramfb",
      "-smbios", "type=1,serial={{.Hostname}}",
    ]
    qe.qemu_dir = qemu_dir if qemu_dir
  end
end
`))
